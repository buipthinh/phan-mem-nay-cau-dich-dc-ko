export const messages: Record<Lang, Messages> = { vi, en, zh, ko };

/** Dịch một khoá giao diện, thay {{biến}} bằng giá trị trong `vars`. */
export function translate(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = messages[lang][key] ?? messages.vi[key];
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ''));
}
